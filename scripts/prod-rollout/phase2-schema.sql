CREATE OR REPLACE FUNCTION public.upsert_level_clear_time(p_level smallint, p_clear_time_ms integer)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  uid uuid := auth.uid();
BEGIN
  IF uid IS NULL THEN
    RAISE EXCEPTION 'not authenticated';
  END IF;
  IF p_level IS NULL OR p_level < 1 THEN
    RAISE EXCEPTION 'invalid level';
  END IF;
  IF p_clear_time_ms IS NULL OR p_clear_time_ms < 1 THEN
    RAISE EXCEPTION 'invalid clear time';
  END IF;

  INSERT INTO public.level_clear_time (user_id, level, clear_time_ms, achieved_at)
  VALUES (uid, p_level, p_clear_time_ms, now())
  ON CONFLICT (user_id, level)
  DO UPDATE SET
    clear_time_ms = EXCLUDED.clear_time_ms,
    achieved_at = EXCLUDED.achieved_at
  WHERE EXCLUDED.clear_time_ms < level_clear_time.clear_time_ms;
END;
$function$;

CREATE OR REPLACE FUNCTION public.get_top_10_level_clear_times(p_level smallint)
 RETURNS TABLE(standing bigint, clear_time_ms integer, user_name text, avatar_url text, is_current_user boolean)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
BEGIN
  RETURN QUERY
  SELECT
    ROW_NUMBER() OVER (ORDER BY fastest.clear_time_ms ASC, fastest.achieved_at ASC)::bigint,
    fastest.clear_time_ms,
    COALESCE(u.raw_user_meta_data->>'name', ''),
    COALESCE(u.raw_user_meta_data->>'avatar_url', ''),
    (fastest.user_id = auth.uid())
  FROM (
    SELECT lct.user_id, lct.clear_time_ms, lct.achieved_at
    FROM public.level_clear_time lct
    WHERE lct.level = p_level
    ORDER BY lct.clear_time_ms ASC, lct.achieved_at ASC
    LIMIT 10
  ) fastest
  JOIN auth.users u ON u.id = fastest.user_id;
END;
$function$;

CREATE OR REPLACE FUNCTION public.get_user_level_clear_time(p_level smallint)
 RETURNS TABLE(standing bigint, clear_time_ms integer, user_name text, avatar_url text, is_current_user boolean)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  uid uuid := auth.uid();
  mine_ms integer;
  mine_at timestamptz;
BEGIN
  IF uid IS NULL THEN
    RETURN;
  END IF;

  SELECT lct.clear_time_ms, lct.achieved_at
  INTO mine_ms, mine_at
  FROM public.level_clear_time lct
  WHERE lct.user_id = uid AND lct.level = p_level;

  IF mine_ms IS NULL THEN
    RETURN;
  END IF;

  RETURN QUERY
  SELECT
    (
      SELECT COUNT(*) + 1
      FROM public.level_clear_time o
      WHERE o.level = p_level
        AND (
          o.clear_time_ms < mine_ms
          OR (o.clear_time_ms = mine_ms AND o.achieved_at < mine_at)
        )
    )::bigint,
    mine_ms,
    COALESCE(u.raw_user_meta_data->>'name', ''),
    COALESCE(u.raw_user_meta_data->>'avatar_url', ''),
    true
  FROM auth.users u
  WHERE u.id = uid;
END;
$function$;

