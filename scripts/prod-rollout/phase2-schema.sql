CREATE OR REPLACE FUNCTION public.upsert_issue_rating(p_issue_id bigint, p_stars smallint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  uid uuid := auth.uid();
  old_stars smallint;
BEGIN
  IF uid IS NULL THEN
    RAISE EXCEPTION 'not authenticated';
  END IF;
  IF p_issue_id IS NULL OR p_issue_id < 1 THEN
    RAISE EXCEPTION 'invalid issue';
  END IF;
  IF p_stars IS NULL OR p_stars < 1 OR p_stars > 5 THEN
    RAISE EXCEPTION 'invalid stars';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.story_issue WHERE id = p_issue_id AND active = true) THEN
    RAISE EXCEPTION 'issue not found';
  END IF;

  SELECT stars INTO old_stars
  FROM public.story_issue_rating
  WHERE user_id = uid AND issue_id = p_issue_id;

  IF old_stars IS NOT NULL AND old_stars = p_stars THEN
    RETURN;
  END IF;

  IF old_stars IS NULL THEN
    INSERT INTO public.story_issue_rating (user_id, issue_id, stars, updated_at)
    VALUES (uid, p_issue_id, p_stars, now());
    UPDATE public.story_issue
    SET rating_sum = rating_sum + p_stars,
        rating_count = rating_count + 1
    WHERE id = p_issue_id;
  ELSE
    UPDATE public.story_issue_rating
    SET stars = p_stars,
        updated_at = now()
    WHERE user_id = uid AND issue_id = p_issue_id;
    UPDATE public.story_issue
    SET rating_sum = rating_sum - old_stars + p_stars
    WHERE id = p_issue_id;
  END IF;
END;
$function$;

