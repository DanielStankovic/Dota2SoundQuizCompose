CREATE OR REPLACE FUNCTION public.upsert_journey_assist_unlock(
  p_level smallint,
  p_count_unlocked boolean,
  p_primer_unlocked boolean
)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  uid uuid := auth.uid();
BEGIN
  IF uid IS NULL THEN
    RAISE EXCEPTION 'not authenticated';
  END IF;
  IF p_level IS NULL OR p_level < 1 THEN
    RAISE EXCEPTION 'invalid level';
  END IF;
  IF NOT COALESCE(p_count_unlocked, false) AND NOT COALESCE(p_primer_unlocked, false) THEN
    RAISE EXCEPTION 'no unlock flags';
  END IF;

  INSERT INTO public.journey_assist_unlock (
    user_id, level, count_unlocked, primer_unlocked, updated_at
  )
  VALUES (
    uid,
    p_level,
    COALESCE(p_count_unlocked, false),
    COALESCE(p_primer_unlocked, false),
    now()
  )
  ON CONFLICT (user_id, level)
  DO UPDATE SET
    count_unlocked = journey_assist_unlock.count_unlocked OR EXCLUDED.count_unlocked,
    primer_unlocked = journey_assist_unlock.primer_unlocked OR EXCLUDED.primer_unlocked,
    updated_at = now();
END;
$function$;

